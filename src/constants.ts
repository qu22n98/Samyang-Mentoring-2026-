export const BI_MONTHLY_PERIODS = [
  { name: '6월-7월', startMonth: 5, endMonth: 6 },
  { name: '8월-9월', startMonth: 7, endMonth: 8 },
  { name: '10월-11월', startMonth: 9, endMonth: 10 },
];

export const getBiMonthlyPeriod = (date: Date) => {
  const month = date.getMonth() + 1; // 1-indexed for easier comparison
  const day = date.getDate();

  // Phase 1: May (>=27), June, July
  if ((month === 5 && day >= 27) || month === 6 || month === 7) {
    return BI_MONTHLY_PERIODS[0];
  }
  // Phase 2: August, September
  if (month === 8 || month === 9) {
    return BI_MONTHLY_PERIODS[1];
  }
  // Phase 3: October, November
  if (month === 10 || month === 11) {
    return BI_MONTHLY_PERIODS[2];
  }

  return undefined;
};
